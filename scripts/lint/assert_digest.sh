#!/usr/bin/env bash
# Дайджест УТВЕРЖДЕНИЙ для человеческого ревью.
#
# Зачем. Главный потолок контура (Delivery §3.1d): гейты проверяют соответствие
# объявленному, но не верность объявленного. `assert f(2) == 5` пройдёт всё — тест
# есть, исполняется, что-то утверждает, мутанта убивает. Отличить верное ожидание
# от неверного может только человек.
#
# Значит задача контура — не заменить это чтение, а сделать его ДЕШЁВЫМ. Утверждения
# — это 2-3% диффа, но именно в них живёт ошибка ожидания. Читать 15 утверждений
# вместо 400 строк кода реально; читать 400 строк никто не будет.
#
# Это НЕ гейт: он ничего не запрещает, exit 0. Вне git-репозитория дайджеста нет — там
# отказ, а не ноль (`cqg@3.13`). Его продукт — текст в verify-report.md, под которым
# человек ставит подпись (DoD §3.2 для M/L).
#
# Настройка (env): BASE (origin/main), LINT_TEST_GLOB — маски тест-файлов через
# пробел (дефолт ниже; обещана шапкой с первой редакции, подключена с `cqg@2.68`),
# LINT_SPEC — спека, к примерам которой привязывают (delivery/active/spec.md;
# поставку, которую архивирует этот же дифф, сверяют с её спекой в архиве).
#
# Использование:
#   bash scripts/lint/assert_digest.sh                    # в stdout
#   bash scripts/lint/assert_digest.sh >> delivery/active/verify-report.md

set -uo pipefail

BASE=${BASE:-origin/main}
REPO_ROOT=$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd -P); unset GIT_DIR GIT_WORK_TREE   # дерево гейта, §6
[[ "${GIT_INDEX_FILE:-}" == /* && "${GIT_INDEX_FILE%/*}" -ef "$(git -C "$REPO_ROOT" rev-parse --absolute-git-dir 2>/dev/null)" ]] || unset GIT_INDEX_FILE
cd "$REPO_ROOT" || exit 1

# Вне git-репозитория «ref недоступен» выходило нулём (`cqg@3.13`).
if ! git rev-parse --git-dir >/dev/null 2>&1; then
  echo "assert_digest: вне git-репозитория — судить нечего: это не «нарушений нет» (дерево $REPO_ROOT)" >&2
  exit 1
fi

if ! git rev-parse --verify --quiet "$BASE" >/dev/null; then
  echo "assert_digest: ref '$BASE' недоступен" >&2
  exit 0
fi

# Тест-файлы диффа ЦЕЛИКОМ (`-U` длиннее любого файла): судят только ДОБАВЛЕННЫЕ
# утверждения — изменённое утверждение и есть новое ожидание, — а метку читают по
# всему блоку теста (`cqg@2.83`). Прежде разбор видел одни строки `+` подряд, через
# границы файлов и ханков: метка на неизменной строке `def test…` не засчитывалась,
# а утверждение, дописанное в чужой непомеченный тест, наследовало метку блока,
# добавленного выше, — то есть `n/a` над ожиданием, которого никто не подписывал.
# JS — вся родня, которую разбор узнаёт по расширению (`js` ниже, `cqg@3.29`): тест
# `*.test.mjs` уходил в «не разбирал» (первый проект на `cqg@3.14`).
read -r -a TEST_GLOBS <<< "${LINT_TEST_GLOB:-*test*.py *test*.ts *test*.tsx *test*.mts *test*.cts *test*.js *test*.jsx *test*.mjs *test*.cjs *_test.go *Tests.swift *Test.swift}"
diff_text=$(git diff --no-color --no-ext-diff --unified=1000000 "$BASE"...HEAD \
  -- "${TEST_GLOBS[@]}" 2>/dev/null)

# Примеры — id из первой колонки таблиц спеки, грамматика та же, что у
# `delivery_check` (`| A1 | …`; `EX1` и `A.1` — не id). Привязка — только к ним
# (`cqg@2.83`). Поле Smart Friend Ally 23.10: метка урока «(L90)» в комментарии
# записала четыре утверждения к «примеру L90» — разбор брал любой токен «буква +
# цифры», и сводка печатала «✅ каждое ведёт к примеру» и 0, то есть `n/a` над
# ожиданиями, которых человек не подписывал. Спеки нет — сверять не с чем: метка
# помечается `?`, и маркер `unknown`.
SPEC=${LINT_SPEC:-delivery/active/spec.md}
spec_ids=""
if [[ -f "$SPEC" ]]; then
  spec_ids=$(awk 'match($0, /^[ \t]*[|][ \t]*[A-Z][0-9]+[ \t]*[|]/) {
      s = substr($0, RSTART, RLENGTH); gsub(/[^A-Z0-9]/, "", s); print s }' "$SPEC" \
    | sort -u | paste -sd' ' -)
fi

# «Не видел» обязано отличаться от «утверждений нет» (`cqg@2.68`). Поле Smart Friend
# Ally 18.10: в диффе 12 `XCTAssert`, а сводка — «Новых утверждений нет» и 0
# непривязанных, то есть `asserts_reviewed_by: n/a` проходил на пустоте: маска не
# знала Swift. Тест-файл опознаётся ПРИНЦИПОМ — именем (`test_*`, `*_test.*`,
# `*_spec.*`, `*.test.*`, `*Tests.*`, `*Spec.*`) или каталогом `__tests__/`, где имена
# не помечены, — а не списком языков. Каталог `tests/` сам по себе признаком не
# служит: на том же поле он дал бы `unknown` генератору фикстур
# `Tests/…/Fixtures/make_fixtures.py`. Файл мимо масок выше разобран не был, и
# маркер тогда `unknown`, а не число. Оба списка — с `-z` (`cqg@3.01`): кириллический
# тест-файл в кавычках не кончался расширением и выпадал из «не видел».
unseen=$(comm -23 \
  <(git diff --name-only -z --diff-filter=d "$BASE"...HEAD 2>/dev/null | tr '\0' '\n' \
      | grep -E '\.(py|pyi|ts|tsx|js|jsx|mjs|cjs|mts|cts|go|swift|kt|kts|java|rb|php|cs|rs|scala|dart|m|mm|c|cc|cpp|h)$' \
      | grep -E '(^|/)__tests__/|(^|/)(test_[^/]*|[^/]*_(test|spec)\.[^/]*|[^/]*\.(test|spec)\.[^/]*|[^/]*(Tests?|Spec)\.[^/]*)$' \
      | sort -u) \
  <(git diff --name-only -z --diff-filter=d "$BASE"...HEAD -- "${TEST_GLOBS[@]}" 2>/dev/null \
      | tr '\0' '\n' | sort -u))

# Маркер — последней строкой: его дописывают в verify-report, и его же читает
# delivery_check. Неразобранный тест-файл или метка, которую не с чем сверить,
# делают число непроверенным — `unknown`.
marker() {
  if [[ -n "$unseen" ]]; then
    echo "⚠ **Тест-файлы, которых дайджест не разбирал** (маски — \`LINT_TEST_GLOB\`):"
    printf '%s\n' "$unseen" | sed 's/^/- `/; s/$/`/'
    echo "Их утверждений здесь нет, поэтому число непривязанных неизвестно, и"
    echo "\`asserts_reviewed_by: n/a\` недоступно: подпись human:… at=… либо маски проекта."
    echo
    echo "asserts_without_example: unknown"
  elif [[ "${unsure:-0}" -gt 0 ]]; then
    echo "asserts_without_example: unknown"
  else
    echo "asserts_without_example: $1"
  fi
}

# Классификация каждого добавленного утверждения: привязано к примеру спеки или нет.
#
# Привязка считается ПО ТЕСТ-БЛОКУ, а не по строке утверждения: id пишут в имени
# или комментарии теста (`def test_empty_robots():  # A1`), а сам assert его не
# содержит. Классификация по строке давала бы «непривязано» на каждом честном
# тесте — ложное срабатывание, после которого инструмент перестают запускать
# (Delivery §4.3b). Чужой токен (`L90`, `H1`) метку блока не сбрасывает и не
# заменяет.
#
# Метка живёт в блоке, где написана, а границу блока даёт ОТСТУП (`cqg@2.92`). Прежде
# метка жила до начала следующего теста, и помощник ниже помеченного теста или шапки
# файла её наследовал: на тест-файлах флота 26.10 так «привязаны» 108 утверждений из
# 7641 — у Smart Friend Ally помощники с `file:line:` под тестами, у Ahrefs и G connect
# помощники под меткой шапки. Тест кончается на первом операторе на своём отступе или
# левее; скобка (и закрывающая кавычка шаблона), комментарий и пустая строка блок не
# закрывают, «начало теста» внутри открытого (`test.step(…)`) — его строка. Вне теста
# метка строки-заголовка (код кончается `:` или `{`) живёт в её теле, метка строки тела
# — до конца объемлющего блока, метка комментария или аннотации (`@Test("…")` над
# `func`) — у объявления под ним. Вложенный помощник — часть теста: сброс на любом `def`
# обвинил бы его. Помощнику с утверждениями нужна своя метка. Метка вплотную НАД тестом —
# комментарий, декоратор, случай в его аргументах — тоже его (`cqg@2.93`): начало теста
# её больше не сбрасывает.
#
# Начало теста — объявление (`def test…`, `func test…`, аннотация `@Test`) или ВЫЗОВ
# тест-функции (`cqg@3.03`): голова цепочки — сам `it`/`test`, за ней любые модификаторы
# — `it.each([…])(…)`, `it.skipIf(…)(…)`, `test.only(…)`, таблица-шаблон после `.each`.
# Прежде узнавалась одна форма `it(`, и тест с модификатором разбирался как блок вне
# теста: метку `describe` он брал, а голый `it(` рядом — нет (G connect 26.10: 6
# утверждений), метка в его теле жила до следующего оператора. Член — не голова:
# `/…/.test(s)` — метод регэкспа. Набор под `test.` (`test.describe` Playwright) — не тест,
# как и `describe`: тестом он слил бы свои тесты в один, и метка ушла бы к соседу.
# Модификаторы — форма JS/TS (по расширению файла): в Kotlin `it.` — параметр лямбды, и
# `it.check()` открыл бы тест посреди помощника; голый `it(…)` — тест и там (Kotest, Quick).
#
# Ссылка на пример — то же понятие, что `example_ref_pattern` Delivery, одно на три
# проверки (матрицу форм держит `test_assert_digest_binds_to_examples.py`): id
# отделён от слова, `%` перед ним — байт URL-кодировки, id целиком в кавычках —
# значение поля, а не пометка. Границы — вручную, а НЕ `\b`: BSD-grep/awk на macOS
# `\b` в ERE не поддерживают, и выражение молча не находит ничего. Побочно это
# отсеивает `MD5`/`UTF8`: там перед цифрой буква внутри слова. Класс «буква слова» —
# выражением, а не строкой-алфавитом: 63 знака подряд detect-secrets метит как
# Base64-секрет, и payload краснел бы под собственным гейтом проекта (§2.7).
#
# Разбор — по БАЙТАМ (`LC_ALL=C`, `cqg@2.94`): всё, что он ищет, — ASCII, а awk macOS под
# UTF-8-локалью падал на многобайтном знаке вплотную перед id («P1» в ёлочках, №P1), и
# скрипт, не глядя на код возврата, печатал досчитанное до падения — вплоть до
# «утверждений нет» и 0. Упавший разбор — `unknown` (ниже).
classified=$(printf '%s\n' "$diff_text" | LC_ALL=C awk -v ids="$spec_ids" -v have_spec="$([[ -f "$SPEC" ]] && echo 1)" '
  BEGIN {
    Q = "\"\047`"; REQ = "(^|[^a-zA-Z_.])require[ \t]*[(]?[ \t]*[" Q "]"
    n = split(ids, a, " "); for (i = 1; i <= n; i++) known[a[i]] = 1
  }
  # Первая ссылка строки на пример; без спеки — первый кандидат с пометкой «?».
  function ref(s,    pc, lc, rc, tok) {
    pc = ""
    while (match(s, /[A-Z][0-9]+/)) {
      lc = (RSTART > 1) ? substr(s, RSTART - 1, 1) : pc
      rc = substr(s, RSTART + RLENGTH, 1)
      tok = substr(s, RSTART, RLENGTH)
      pc = substr(s, RSTART + RLENGTH - 1, 1)
      s = substr(s, RSTART + RLENGTH)
      if (lc == "%" || lc ~ /[A-Za-z0-9_]/ || rc ~ /[A-Za-z0-9_]/) continue
      if (lc != "" && rc != "" && index(Q, lc) && index(Q, rc)) continue
      if (!have_spec) return tok "?"
      if (tok in known) return tok
    }
    return ""
  }
  # Состояние разбора: cur/t — метка и отступ открытого теста; olab/oh — метка вне
  # теста и отступ её блока; pend/pind — метка и отступ серии комментариев и аннотаций
  # над объявлением; sd[1..ns] — отступы открытых операторов.
  function reset() { cur = olab = pend = ""; t = oh = pind = -1; ns = 0 }
  /^diff --git / { body = 0; js = ($0 ~ /\.(ts|tsx|mts|cts|js|jsx|mjs|cjs)"?$/); next }
  /^@@/ { body = 1; reset(); next }
  !body || /^[-\\]/ { next }
  {
    added = (substr($0, 1, 1) == "+")
    line = substr($0, 2)
    match(line, /^[ \t]*/); d = RLENGTH; s = substr(line, d + 1); c = substr(s, 1, 1)
    code = s; sub(/[ \t]+(#|\/\/).*$/, "", code); sub(/[ \t]+$/, "", code)
    blank = (s == ""); com = (s ~ /^(#|\/\/|\/\*|\*)/); clo = (c != "" && index(")]}`", c) > 0)
    opener = (!com && code ~ /[:{]$/); deco = (c == "@" && !opener); stmt = !(blank || com || clo)
    # Тест закрывает первый оператор на его отступе или левее.
    if (t >= 0 && stmt && d <= t) { t = -1; cur = "" }
    if (oh >= 0 && stmt && d <= oh) { olab = ""; oh = -1 }
    par = -1
    if (stmt) { while (ns > 0 && sd[ns] >= d) ns--; if (ns > 0) par = sd[ns]; sd[++ns] = d }
    call = match(line, /(^|[^a-zA-Z_.])(it|test)((\.[a-zA-Z_][a-zA-Z0-9_]*)*\(|(\.[a-zA-Z_][a-zA-Z0-9_]*)+`)/)
    head = call ? substr(line, RSTART, RLENGTH) : ""
    call = call && (head ~ /(it|test)\($/ || js && head !~ /\.describe/)
    start = (t < 0 && (call || line ~ /(^|[^a-zA-Z_])(def[ \t]+test|func[ \t]+[Tt]est)|@Test/))
    if (start) { t = d; cur = (pind == d) ? pend : "" }
    r = ref(line)
    # Строка глубже серии и скобка на её отступе — аргументы аннотации: метка её.
    cont = (!com && !deco && !blank && pind >= 0 && (d > pind || clo))
    if (r != "" && (com || deco || cont)) pend = r
    if (t >= 0 && (start || d > t || (d == t && clo))) {
      if (r != "") cur = r
    } else if ((stmt && !deco) || (clo && r != "")) {
      # Вне теста: заголовок держит метку в своём теле, строка тела — до конца
      # объемлющего блока; поздняя ссылка метку меняет, а блок не сужает.
      lab = (r != "") ? r : ((pind == d) ? pend : "")
      h = (opener || r == "" || par < 0) ? d : par
      if (lab != "") { olab = lab; oh = (oh >= 0 && h > oh) ? oh : h }
    }
    if (blank) { pend = ""; pind = -1 }
    else if (com || deco) { if (pind < 0) pind = d }
    else if (stmt && (pind < 0 || d <= pind)) { pend = ""; pind = -1 }
    # Утверждение — и метод объекта-утверждения (`assert.equal(` у node:assert, chai,
    # testify); подключение модуля — нет: `import … assert …`, `require("…")` (`cqg@3.29`).
    imp = (s ~ /^(import|from)[ \t]/ || line ~ REQ)
    if (added && !imp && line ~ /(^|[^a-zA-Z_])(assert[a-zA-Z_]*(\.[a-zA-Z_][a-zA-Z0-9_]*)*|XCTAssert[a-zA-Z]*|XCTFail|expect|require|should)[ (]/) {
      lab = (t >= 0) ? cur : olab
      sub(/^[ \t]+/, "", line)
      printf "%s\t%s\n", (lab == "" ? "-" : lab), line
    }
  }
')
parse_rc=$?

echo "## Assertion digest (ревью ожиданий, не кода)"
echo
echo "База: \`$BASE\` · сгенерировано \`assert_digest.sh\`"
echo

if [[ "$parse_rc" -ne 0 ]]; then
  echo "⚠ **Разбор упал** (awk, код $parse_rc): утверждения не досчитаны, число"
  echo "непривязанных неизвестно, и \`n/a\` не заслужен — подпись human:… at=…"
  echo
  echo "asserts_without_example: unknown"
  exit 0
fi

if [[ -z "$classified" ]]; then
  # `asserts_without_example: N` — не отчёт, а ВХОД В РЕШЕНИЕ: `delivery_check`
  # разрешает `asserts_reviewed_by: n/a` только при N = 0 (§3.1d уровень 3). Значит
  # «утверждений нет» из-за незакоммиченного теста = разрешение подписать пустоту.
  # Класс уже закрыт у `check_diff_coverage.sh` и `check_grep_gate.sh`; здесь его
  # не было, и приёмочное развёртывание поймало это staged-тестом с `assert 2+2==5`.
  staged=$(git status --porcelain -z --no-renames -- "${TEST_GLOBS[@]}" 2>/dev/null \
    | tr '\0' '\n' | wc -l | tr -d ' ')
  if [[ "${staged:-0}" -gt 0 ]]; then
    echo
    echo "⚠ **Внимание: $staged незакоммиченных тест-файл(ов).** Дайджест считает"
    echo "ЗАКОММИЧЕННЫЙ дифф, поэтому их утверждений здесь нет. Закоммить и повторить"
    echo "до того, как ставить \`asserts_reviewed_by: n/a\` — иначе n/a подписывает пустоту."
    echo
  fi
  echo "**Новых утверждений нет.**"
  echo
  echo "Это либо тесты не добавлялись (тогда чем закрыт DoD?), либо изменения"
  echo "только в реализации. Второе законно; первое — повод спросить."
  echo
  # Маркер печатается ВСЕГДА, в том числе здесь: delivery_check требует его
  # наличия, а «утверждений нет» — законный ноль непривязанных.
  marker 0
  exit 0
fi

n=$(printf '%s\n' "$classified" | wc -l | tr -d ' ')
bare=$(printf '%s\n' "$classified" | grep -c '^-	' || true)
bare=${bare:-0}
# Метка, которую не с чем сверить (`?`), — ни «привязано», ни «нет».
unsure=$(printf '%s\n' "$classified" | cut -f1 | grep -c '?$' || true)
unsure=${unsure:-0}

echo "Новых/изменённых утверждений: **$n**, из них без ссылки на пример спеки:"
echo "**$bare**. Вопрос к каждому непривязанному один: **откуда взято ожидаемое"
echo "значение — из спеки или придумано под реализацию?**"
echo
echo '```'
printf '%s\n' "$classified" | cut -c1-160
echo '```'
echo
if [[ -f "$SPEC" ]]; then
  echo "Примеры спеки (\`$SPEC\`): ${spec_ids:-ни одного id в первой колонке таблиц}."
  echo
fi
ids=$(printf '%s\n' "$classified" | cut -f1 | grep -v '^-$' | sort -u | paste -sd' ' -)
if [[ "$unsure" -gt 0 ]]; then
  echo "⚠ **Спеки нет** (\`$SPEC\`, ручка \`LINT_SPEC\`): метки с \`?\` не с чем сверить —"
  echo "id урока или задачи выглядит так же, как id примера. Число непривязанных"
  echo "неизвестно, и \`n/a\` не заслужен: подпись human:… at=… либо путь к спеке."
elif [[ "$bare" -eq 0 && -n "$unseen" ]]; then
  # Совет «пиши n/a» тут был бы ложью: часть тест-файлов не разобрана (ниже).
  echo "Разобранные утверждения ведут к примерам спеки ($ids), но разобраны НЕ все"
  echo "тест-файлы — список ниже, и до него \`n/a\` не заслужен."
elif [[ "$bare" -eq 0 ]]; then
  echo "✅ **Каждое утверждение ведёт к примеру спеки** ($ids), а примеры человек"
  echo "подписал до кода (\`human_ok_spec\`). Подпись под дайджестом здесь"
