"""Ветка-проба A109: функция, которую тест зовёт без утверждений, — мутанты выживают.

Мутанты `value * 3 + 1` (знаки `/` и `-`, числа 4 и 2) при вызове не падают, а возвращают другое
значение: тест без утверждения их не замечает. `max`/`min` для пробы не годятся: мутанты mutmut
3.8.1 подставляют в вызов `None` или выбрасывают аргумент и падают с TypeError — тест краснеет и
без утверждений (проба второй проверяющей, прогон 44725944177: «убито 8 из 8»).
"""


def scale(value: int) -> int:
    """Значение, умноженное на три, плюс один."""
    return value * 3 + 1
