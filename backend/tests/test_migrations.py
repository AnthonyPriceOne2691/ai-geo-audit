#: Вид находки узнаётся по шаблону её текста; сравниваются вид и номер, а не сообщение целиком.
KINDS = {
    "пропуск": re.compile(r"номер (\d{4}) пропущен$"),
    "повтор": re.compile(r"номер (\d{4}) у нескольких ревизий: "),
}


def kind_and_number(problem: str) -> tuple[str, str]:
    """Вид и номер находки; находка другого вида — («другое», текст целиком): сравнение она не
    пройдёт и видна в отчёте."""
    for kind, pattern in KINDS.items():
        if found := pattern.match(problem):
            return kind, found.group(1)
    return "другое", problem


def chain_model(numbers: list[int]) -> list[tuple[str, str]]:
    """Находки модели: пропуск — номер до наибольшего, которого нет ни у одной ревизии; повтор —
    номер у двух ревизий и больше."""
    counts = Counter(numbers)
    gaps = [("пропуск", f"{n:04d}") for n in range(1, max(counts) + 1) if n not in counts]
    repeats = [("повтор", f"{n:04d}") for n, count in counts.items() if count > 1]
    return sorted(gaps + repeats)


@settings(max_examples=200)
@given(numbers=st.lists(st.integers(1, 9), min_size=1, max_size=10))
def test_a119_findings_are_exactly_the_model_gaps_and_repeats(numbers: list[int]) -> None:
    """A119: свойство над `chain_problems` — номера ревизий со случайными пропусками и повторами, у
    каждой `down_revision` на номер раньше; находки — ровно пропуски и повторы модели, сравниваются
    вид и номер. Каталог — временный у примера: `tmp_path` живёт весь тест, а не один пример."""
    with tempfile.TemporaryDirectory() as folder:
        versions = Path(folder)
        for i, n in enumerate(numbers):
            write(versions, f"{n:04d}_{i}.py", f"{n:04d}", f"{n - 1:04d}" if n > 1 else None)
        found = sorted(kind_and_number(problem) for problem in revisions.chain_problems(versions))
    assert found == chain_model(numbers)


